    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // selected row
        int selectedRow = jTable3.getSelectedRow();
        // if none selected, show message
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a transaction from the table to update.");
            return;
        }
        try {
            // got transaction info from selected row
            int transactionId = Integer.parseInt(tableModel.getValueAt(selectedRow, 0).toString()); // comes as object so converted
            Timestamp date = (Timestamp) tableModel.getValueAt(selectedRow, 1);  // Date is in column 1, got automatically
            String addedBy = (String) tableModel.getValueAt(selectedRow, 2);      // addedBy is in column 2, got automatically

            // got new values
            String type = (String) jComboBox4.getSelectedItem();
            String category = (String) jComboBox5.getSelectedItem();
            double amount = Double.parseDouble(jSpinner2.getValue().toString());
            String currency = (String) jComboBox6.getSelectedItem();
            String description = jTextArea2.getText().trim();

            // created my object according to the data I got
            Transaction transaction = new Transaction(transactionId, date, addedBy, type, category, amount, currency, description);
            // gave the rest to the manager object, function handled my object
            transactionManager.update(transaction);
            // reloaded my table
            transactionManager.loadData(tableModel);
            // showed my message
            JOptionPane.showMessageDialog(this, "Transaction updated successfully.");

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Please enter valid numeric values.");
        }

    }//GEN-LAST:event_jButton4ActionPerformed

