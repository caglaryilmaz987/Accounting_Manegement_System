    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
// selected row
        int selectedRow = jTable3.getSelectedRow();
// if a row is selected
        if (selectedRow != -1) {
            int id = (int) jTable3.getValueAt(selectedRow, 0); // getting the id from the table at index 0
            // ask for confirmation
            int confirm = JOptionPane.showConfirmDialog(
                    null,
                    "Are you sure you want to delete this transaction?",
                    "Confirm Delete",
                    JOptionPane.YES_NO_OPTION
            );
            // if confirm equals yes
            if (confirm == JOptionPane.YES_OPTION) {
                // deleted from the database
                transactionManager.delete(id);

                // refreshed the table
                transactionManager.loadData(tableModel);

                // informed the user
                JOptionPane.showMessageDialog(null, "Transaction deleted and table refreshed.");

                // asked if user wants to delete another transaction
                int answer = JOptionPane.showConfirmDialog(
                        null,
                        "Do you want to delete another transaction?",
                        "Delete Another?",
                        JOptionPane.YES_NO_OPTION
                );

                if (answer == JOptionPane.YES_OPTION) {
                    // did nothing, stayed on the same screen
                    return;
                } else {
                    // returned user to their screen
                    dispose();
                    if (Login_Screen.usertype == "admin") {
                        Admin_Screen s2 = new Admin_Screen();
                        s2.setVisible(true);
                    } else {
                        User_Screen s1 = new User_Screen();
                        s1.setVisible(true);
                    }
                }
            }
        }

    }//GEN-LAST:event_jButton5ActionPerformed

    private void jMenuItem6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem6ActionPerformed
        // TODO add your handling code here:
// Getting the component that the popup menu is attached to using the invoker
        Component comp = jPopupMenu1.getInvoker();

// If the component is a text component
        if (comp instanceof JTextComponent) {
            // Get the selected text
            String selectedText = ((JTextComponent) comp).getSelectedText(); // casting component to text component here

            // If there is selected text
            if (selectedText != null) {
                // Copy the selected text to the clipboard
                StringSelection selection = new StringSelection(selectedText);
                // Get the toolkit object, access clipboard and put the selection in the clipboard
                Toolkit.getDefaultToolkit().getSystemClipboard().setContents(selection, null);
            }
        }


    }//GEN-LAST:event_jMenuItem6ActionPerformed

    private void jMenuItem14ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem14ActionPerformed
// Getting the component to which the popup menu is attached using the invoker
        Component comp = jPopupMenu1.getInvoker();

// Getting the system clipboard
        Clipboard clipboard = Toolkit.getDefaultToolkit().getSystemClipboard();

        try {
            // Getting the text data from the clipboard, casting the object to String using string flavor
            String pasteString = (String) clipboard.getData(DataFlavor.stringFlavor);

            // If the component is a text component
            if (comp instanceof JTextComponent) {
                // Replacing the selected text with the pasted text
                ((JTextComponent) comp).replaceSelection(pasteString);
            }

        } catch (Exception ex) {
            ex.printStackTrace();
        }


    }//GEN-LAST:event_jMenuItem14ActionPerformed

