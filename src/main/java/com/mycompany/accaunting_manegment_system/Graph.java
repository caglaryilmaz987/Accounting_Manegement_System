    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // Get the logged-in username
        String currentUser = Login_Screen.username;

        try (Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/users", "root", "root")) {
            // SQL query: Calculate total income and expense by month and currency
            String query = "SELECT month, currency, "
                    + "SUM(CASE WHEN type = 'Income' THEN amount ELSE 0 END) AS income_total, "
                    + "SUM(CASE WHEN type = 'Expense' THEN amount ELSE 0 END) AS expense_total "
                    + "FROM (SELECT DATE_FORMAT(date, '%Y-%m') AS month, amount, type, currency, added_by FROM transactions WHERE added_by = ?) AS monthly "
                    + "GROUP BY month, currency ORDER BY month, currency";

            // Prepare statement and set parameter
            PreparedStatement stmt = conn.prepareStatement(query);
            stmt.setString(1, currentUser);
            ResultSet rs = stmt.executeQuery();

            // Use StringBuilder to create the report
            StringBuilder report = new StringBuilder();
            report.append("Monthly Income-Expense Report for ").append(currentUser).append(" (TL, USD, EUR)\n");
            report.append("============================================\n\n");

            String currentMonth = "";
            boolean hasData = false;  // Check if there is any data

            // Iterate over result set rows
            while (rs.next()) {
                hasData = true;
                String month = rs.getString("month");           // Month info
                String currency = rs.getString("currency");     // Currency
                double income = rs.getDouble("income_total");   // Total income
                double expense = rs.getDouble("expense_total"); // Total expense
                double net = income - expense;                   // Net balance

                // When month changes, add new month header to the report
                if (!month.equals(currentMonth)) {
                    currentMonth = month;
                    report.append("Month: ").append(month).append("\n");
                    report.append("----------------------------\n");
                }

                // Add income, expense, and net per currency to the report
                report.append("Currency: ").append(currency).append("\n");
                report.append("  Income : ").append(String.format("%.2f", income)).append(" ").append(currency).append("\n");
                report.append("  Expense: ").append(String.format("%.2f", expense)).append(" ").append(currency).append("\n");
                report.append("  Net    : ").append(String.format("%.2f", net)).append(" ").append(currency).append("\n\n");
            }

            // If no data found, inform the user
            if (!hasData) {
                report.append("No transaction data found for user ").append(currentUser).append(".\n");
            }

            // Open file chooser dialog
            JFileChooser fileChooser = new JFileChooser();
            fileChooser.setDialogTitle("Save Report");       // Dialog title
            fileChooser.setSelectedFile(new File("monthly_report.txt"));  // Default file name

            int userSelection = fileChooser.showSaveDialog(null);

            // If user approves, write report to file
            if (userSelection == JFileChooser.APPROVE_OPTION) {

                File fileToSave = fileChooser.getSelectedFile();

                try (FileWriter writer = new FileWriter(fileToSave)) {
                    writer.write(report.toString());  // Write report to file
                    JOptionPane.showMessageDialog(null, "File saved successfully:\n" + fileToSave.getAbsolutePath());
                } catch (IOException e) {
                    // Inform user on file write error
                    JOptionPane.showMessageDialog(null, "Error writing file:\n" + e.getMessage());
                }
            } else {
                // Inform user if save operation was canceled
                JOptionPane.showMessageDialog(null, "Save operation cancelled.");
            }

        } catch (Exception e) {

            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "An error occurred during export: " + e.getMessage());
        }

    }//GEN-LAST:event_jButton2ActionPerformed

