    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String currentUser = Login_Screen.username;  // Username of the logged-in user
        String currentRole = Login_Screen.usertype; // Role of the logged-in user

        jPanel1.removeAll();    // Remove all components from jPanel1
        jPanel1.revalidate();   // Revalidate panel (for layout updates)
        jPanel1.repaint();      // Repaint the panel to reflect changes

        DefaultCategoryDataset dataset = new DefaultCategoryDataset(); // Create dataset for the chart

        try (Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/users", "root", "root")) {
            String query = "SELECT month, currency, "
                    // Calculate total amount for 'Income' transactions, else 0
                    + "SUM(CASE WHEN type = 'Income' THEN amount ELSE 0 END) AS income_total, "
                    // Calculate total amount for 'Expense' transactions, else 0
                    + "SUM(CASE WHEN type = 'Expense' THEN amount ELSE 0 END) AS expense_total "
                    // Subquery: select transactions for the user grouped by year-month
                    + "FROM (SELECT DATE_FORMAT(date, '%Y-%m') AS month, amount, type, currency, added_by FROM transactions WHERE added_by = ?) AS monthly "
                    // Group by month and currency and order results accordingly
                    + "GROUP BY month, currency ORDER BY month, currency";

            PreparedStatement stmt = conn.prepareStatement(query);
            stmt.setString(1, currentUser);  // Query only the data for the current user
            ResultSet rs = stmt.executeQuery();

            while (rs.next()) {
                String month = rs.getString("month");       // Month info
                String currency = rs.getString("currency"); // Currency
                double income = rs.getDouble("income_total");   // Total income for the month
                double expense = rs.getDouble("expense_total"); // Total expense for the month
                double net = income - expense;                    // Net balance

                dataset.addValue(net, currency, month); // Add data to the dataset for the chart
            }

        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage()); // Show error message
        }

        String title = "Monthly Net Balance by Currency (" + currentRole + ": " + currentUser + ")"; // Chart title

        JFreeChart chart = ChartFactory.createBarChart(
                title, // Chart title
                "Month", // X-axis label
                "Amount", // Y-axis label
                dataset);       // Dataset

        ChartPanel chartPanel = new ChartPanel(chart);
        chartPanel.setPreferredSize(jPanel1.getSize()); // Set chart panel size to match jPanel1

        jPanel1.setLayout(new java.awt.BorderLayout());          // Set layout to BorderLayout
        jPanel1.add(chartPanel, java.awt.BorderLayout.CENTER);   // Add chart panel to center
        jPanel1.validate();                                       // Validate to update UI

    }//GEN-LAST:event_jButton1ActionPerformed

