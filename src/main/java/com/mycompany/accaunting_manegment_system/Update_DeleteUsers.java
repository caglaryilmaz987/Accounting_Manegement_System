    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        // I got the selected row
        int selectedRow = jTable1.getSelectedRow();
        // if a row is selected
        if (selectedRow != -1) {
            int id = (int) jTable1.getValueAt(selectedRow, 0); // I got the id from the 0th index of the table
            // I showed a confirmation message
            int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this user?", "Confirmation", JOptionPane.YES_NO_OPTION);
            // if yes is selected
            if (confirm == JOptionPane.YES_OPTION) {
                // I sent it to userManager and if successful
                boolean success = userManager.deleteUser(id);
                // this happens
                if (success) {
                    JOptionPane.showMessageDialog(this, "User deleted successfully.");
                    refreshTable();
                } // if not successful
                else {
                    JOptionPane.showMessageDialog(this, "Failed to delete user.");
                }
            }
        } // if no row is selected
        else {
            JOptionPane.showMessageDialog(this, "Please select a user to delete.");
        }

    }//GEN-LAST:event_jButton2ActionPerformed

    private void jMenuItem6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem6ActionPerformed
        // TODO add your handling code here:
        // Getting the component to which the popup menu is attached using the invoker
        Component comp = jPopupMenu1.getInvoker();

        // If the component is a text component
        if (comp instanceof JTextComponent) {
            // Getting the selected text
            String selectedText = ((JTextComponent) comp).getSelectedText(); // casting the component to text component here

            // If there is selected text
            if (selectedText != null) {
                // Copying the selected text to the clipboard
                StringSelection selection = new StringSelection(selectedText);
                // Getting the toolkit object, accessing the clipboard, and placing the selection into the clipboard
                Toolkit.getDefaultToolkit().getSystemClipboard().setContents(selection, null);
            }
        }

    }//GEN-LAST:event_jMenuItem6ActionPerformed

    private void jMenuItem14ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem14ActionPerformed

        // Getting the component to which the popup menu is attached using the invoker
        Component comp = jPopupMenu1.getInvoker();

        // Getting the system clipboard
        Clipboard clipboard = Toolkit.getDefaultToolkit().getSystemClipboard();

        try {
            // Getting the text data from the clipboard, casting it to a string using string flavor
            String pasteString = (String) clipboard.getData(DataFlavor.stringFlavor);

            // If the component is a text component
            if (comp instanceof JTextComponent) {
                // Replacing the selected text with the pasted text
                ((JTextComponent) comp).replaceSelection(pasteString);
            }

        } catch (Exception ex) {
            ex.printStackTrace();
        }


    }//GEN-LAST:event_jMenuItem14ActionPerformed

