private void refreshTable() {
        // I got the model of jTable1 and cast it to DefaultTableModel
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);  // First, I cleared the table
        // I got all users from userManager
        List<User> users = userManager.getAllUsers();
        // I retrieved all properties of my users
        for (User user : users) {
            Object[] row = new Object[]{
                user.getId(),
                user.getUsername(),
                user.getPassword(),
                user.getRole()
            };
            model.addRow(row); // I added the row I created
        }

    }
