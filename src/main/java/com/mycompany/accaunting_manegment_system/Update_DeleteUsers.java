    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int selectedRow = jTable1.getSelectedRow(); // I got the index of the selected row
// if a row is selected
        if (selectedRow != -1) {
            int id = (int) jTable1.getValueAt(selectedRow, 0);  // I got the id from the 0th index
            // I got the necessary info
            String username = jTextField1.getText();
            String password = new String(jPasswordField1.getPassword());
            String role = (String) jComboBox1.getSelectedItem();
            // I sent it to updateUser, if successful
            boolean success = userManager.updateUser(id, username, password, role);
            // success message
            if (success) {
                JOptionPane.showMessageDialog(this, "User updated successfully.");
                refreshTable();

            } // if not successful
            else {
                JOptionPane.showMessageDialog(this, "Failed to update user.");
            }
        } // if no row selected
        else {
            JOptionPane.showMessageDialog(this, "Please select a user to update.");
        }
        // exit


    }//GEN-LAST:event_jButton1ActionPerformed
