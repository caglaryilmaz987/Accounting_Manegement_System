    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {
            // I ask the user to select where to save the backup file using JFileChooser
            JFileChooser chooser = new JFileChooser();
            chooser.setSelectedFile(new File("users_backup.sql")); // I set a default file name

            // If the file selection is not approved, I cancel the operation
            if (chooser.showSaveDialog(this) != JFileChooser.APPROVE_OPTION) {
                return;
            }

            // I get the selected file from the chooser
            File file = chooser.getSelectedFile();

            // I prepare the mysqldump command; mysqldump is used to take backups
            // -u root means the username is root
            // -p + "root" means password is root (no space between -p and password)
            // "users" is the name of the database to back up
            ProcessBuilder pb = new ProcessBuilder(
                    "mysqldump", // path to mysqldump
                    "-u", "root", // username
                    "-p" + "root",// password
                    "users" // database name
            );
            pb.redirectErrorStream(true); // Merge error and output streams
            Process process = pb.start(); // I run the command

            // I write mysqldump output to the file; I read from input stream and write to output stream
            try (InputStream in = process.getInputStream(); OutputStream out = new FileOutputStream(file)) {
                in.transferTo(out); // I finish the copying process
            }

            // If mysqldump process finishes successfully, I inform the user
            if (process.waitFor() == 0) {
                JOptionPane.showMessageDialog(this, "Backup completed successfully.");
            } else {
                // If mysqldump ends with an error, I show an error message to the user
                JOptionPane.showMessageDialog(this, "Backup failed. Please check your credentials and try again.");
            }

        } catch (Exception e) {
            // In case of any exception, I show an error message to the user
            JOptionPane.showMessageDialog(this, "An error occurred: " + e.getMessage());
        }

    }//GEN-LAST:event_jButton2ActionPerformed
