    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        JFileChooser chooser = new JFileChooser();
        // Asking the user to select the backup file

        if (chooser.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
            // If the user selects a file and clicks OK, continue

            File backup = chooser.getSelectedFile();
            // Get the selected backup file

            try {
                String mysqlPath = "mysql"; // Path to the mysql executable

                // Prepare the command line for restoring the database
                ProcessBuilder pb = new ProcessBuilder(mysqlPath, "-u", "root", "-proot", "users");
                // Equivalent to: mysql -u root -proot users

                Process process = pb.start();
                // Start the process

                // Write the contents of the backup file into mysql's input stream
                try (OutputStream os = process.getOutputStream(); FileInputStream fis = new FileInputStream(backup)) {
                    fis.transferTo(os); // Transfer backup file content to mysql process input
                }

                // Read error output if any
                BufferedReader errorReader = new BufferedReader(new InputStreamReader(process.getErrorStream()));
                StringBuilder errorOutput = new StringBuilder();
                String line;
                while ((line = errorReader.readLine()) != null) {
                    errorOutput.append(line).append("\n"); // Collect error lines
                }

                int exitCode = process.waitFor();
                // Wait for the process to finish and get exit code

                if (exitCode == 0) {
                    // Exit code 0 means success
                    JOptionPane.showMessageDialog(this, "Restoration succeeded!");
                } else {
                    // If error occurred, show error message with details
                    JOptionPane.showMessageDialog(this, "Restoration failed. Error:\n" + errorOutput.toString());
                }

            } catch (Exception e) {
                // In case of exceptions, show error message
                JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
            }
        }

    }//GEN-LAST:event_jButton3ActionPerformed

